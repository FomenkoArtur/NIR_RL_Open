"""
Физическая модель участка металлообработки: 8 связанных нелинейных ОДУ.

Модуль дополняет цифровой двойник `plant.py`, но не заменяет его: в `plant.py`
остаются калибровка карт Шухарта, робастная нормализация и веса. Здесь описана
только динамика технологического процесса, поэтому импортируется лишь `numpy`.

Состояние x(t) — восемь показателей в шкале контрольных карт (центр около 100):

    токарная обработка
      x1 — размерная погрешность/износ вершины резца;
      x2 — шероховатость обработанной поверхности Ra;
      x3 — температура в зоне резания;
    фрезерная обработка
      x4 — сила резания (упругое отжатие инструмента);
      x5 — шероховатость обработанной поверхности;
      x6 — амплитуда вибрации (регенеративный чаттер);
    закалка
      x7 — температура заготовки;
      x8 — интенсивность охлаждения / показатель твёрдости.

Показатели приведены к безразмерной шкале карты (100 — центр калибровки).
Для температур это аффинное преобразование, поэтому коэффициенты уравнений
имеют размерность 1/с и допускают единую запись для разных операций.

Принятые допущения (разд. 3.1.1):
  * параметры сосредоточенные, поле температур и напряжений по объёму
    осреднено;
  * тренд износа инструмента и тепловые постоянные меняются медленно по
    сравнению с тактом управления;
  * уставка g(t) — программа обработки, а не константа: при точении и
    фрезеровании она плавно меняется вдоль прохода, при закалке задаёт цикл
    «нагрев → выдержка → охлаждение»;
  * аддитивный шум описывает быстрые флуктуации процесса, детерминированное
    возмущение — тренд износа, скачок вибрации или недостаточное охлаждение.

Все уравнения записаны через отклонения d_i(t) = x_i(t) - g_i(t) от программы.
Поэтому при d = 0 и u = 0 процесс находится на программной траектории, а
возмущения и управление выводят его из равновесия.

Структура уравнений объединяет лучшие решения рецензентов:

  * межкомпонентные связи заданы матрицей коэффициентов c_ij (структура
    кросс-связей между подсистемами): износ → шероховатость, сила резания →
    шероховатость, вибрация → чаттер, температура → интенсивность охлаждения
    и т.д. Нелинейная форма каждого механизма (tanh-насыщение) сохранена,
    а все коэффициенты связей собраны в матрице `c` 8x8;
  * управляющие эффективности собраны в матрице `b` 8x8 (вклад каждого u_j
    в уравнение x_i), а чувствительность к программе — в векторе `k_g`;
    базовая структура каждого канала остаётся вида (-x_i + k_gi*g_i + ...)/TAU_i;
  * износ инструмента — насыщающаяся динамика: w(t) = VB_max*(1 - exp(-t/t_wear)),
    износ растёт и выходит на предел, смещая размер, шероховатость и
    коэффициент самовозбуждения чаттера;
  * автоколебания (чаттер) — уравнение амплитуды Ландау-Стюарта с кубическим
    насыщением: отрицательное демпфирование ограничивает амплитуду биения;
  * цикл закалки — тепловое равновесие по фазам нагрев/выдержка/охлаждение,
    причём фаза охлаждения задана экспоненциальной кривой Ньютона с плавным
    открытием клапана СОЖ;
  * setpoint()/derivatives() поддерживают массивное время: при t формы
    (n,) возвращается g формы (n, 8) и dx/dt формы (n, 8) — это нужно для
    точного расчёта равновесия усреднённым полем;
  * equilibrium() — решение усреднённого по циклу поля методом Рунге-Кутты
    4-го порядка (рефаксация к неподвижной точке осреднённой правой части).
"""

from __future__ import annotations

import numpy as np


class PlantODESystem:
    """Связанная физическая модель 8 показателей участка металлообработки."""

    N_STATES = 8                     # x1...x8
    T_EQUIL = 200.0                  # горизонт осреднения для equilibrium(), с

    # Отображение (i, j) -> имя коэффициента межкомпонентной связи c_ij.
    # Матрица задаёт кросс-связи между подсистемами (разделение вкладов):
    COUPLING_MAP = {
        (0, 2): "a13",   # температура резания -> размерная погрешность
        (1, 0): "a21",   # износ/размер -> шероховатость (точение)
        (1, 2): "a23",   # температура -> шероховатость (насыщение tanh)
        (2, 0): "a31",   # износ -> дополнительный нагрев (трение)
        (2, 1): "a32",   # работа разрушения -> нагрев
        (3, 4): "a45",   # шероховатость -> сила резания
        (3, 5): "a46",   # вибрация -> динамическая сила резания
        (4, 3): "a54",   # сила резания -> шероховатость (tanh)
        (4, 5): "a56",   # следы вибрации -> шероховатость (tanh^2)
        (5, 3): "a64",   # сила резания возбуждает чаттер (tanh)
        (6, 7): "a78",   # интенсивное охлаждение -> снижение температуры
        (7, 6): "a87",   # разность температур -> скорость охлаждения
    }

    # Отображение (i, j) -> (имя коэффициента, знак) матрицы управления b_ij:
    # вклад u_j в правую часть уравнения x_i.
    CONTROL_MAP = {
        (0, 0): ("b1", -1.0),   # коррекция положения резца уменьшает d1
        (1, 1): ("b2", -1.0),   # СОЖ при точении снижает шероховатость
        (2, 1): ("h3", -1.0),   # СОЖ охлаждает зону резания
        (2, 2): ("q3", +1.0),   # скорость резания нагревает
        (3, 3): ("b4", +1.0),   # подача увеличивает силу резания
        (4, 4): ("b5", -1.0),   # СОЖ при фрезеровании
        (5, 5): ("b6", -1.0),   # демпфирование подавляет вибрацию
        (6, 6): ("q7", +1.0),   # мощность нагрева
        (6, 7): ("h7", -1.0),   # расход охлаждающей среды снижает температуру
        (7, 6): ("h8", -1.0),   # избыточный нагрев снижает твёрдость
        (7, 7): ("b8", +1.0),   # расход среды повышает твёрдость
    }

    # Параметры по умолчанию. Любой ключ можно переопределить через params.
    DEFAULTS = {
        # центры контрольных карт (близки к plant.x_bar при BETA = 100)
        "x_nom": np.array([100.03, 100.20, 100.22, 100.40,
                           100.17, 99.97, 100.11, 99.91]),
        # допустимые полосы ±δ_i
        "tol": np.array([1.50, 1.20, 2.50, 1.80, 1.20, 2.20, 3.50, 2.00]),
        # постоянные времени звеньев, с: тепловые процессы инерционнее силовых
        "tau": np.array([18.0, 10.0, 7.0, 9.0, 12.0, 10.0, 35.0, 22.0]),

        # --- токарная обработка ---
        "a13": 0.35,        # тепловое расширение детали/резца -> размерная погрешность
        "wear_gain": 0.18,  # ускоренный износ при перегреве зоны резания
        "wear_scale": 2.0,  # масштаб нелинейности износа
        "a21": 0.45,        # износ резца -> рост шероховатости
        "a23": 0.35,        # температура резания -> рост шероховатости
        "a31": 0.30,        # трение изношенного резца -> дополнительный нагрев
        "a32": 0.20,        # работа разрушения при большой шероховатости -> нагрев
        "q3": 0.60,         # нагрев от скорости резания (управление u3)
        "h3": 0.45,         # охлаждение СОЖ (управление u2)

        # --- фрезерная обработка ---
        "a45": 0.35,        # шероховатость -> сила резания
        "a46": 0.45,        # вибрация -> динамическая сила резания
        "a54": 0.55,        # сила резания -> шероховатость
        "a56": 0.40,        # следы вибрации -> шероховатость
        "a64": 0.60,        # сила резания возбуждает чаттер
        "chat_mu": 1.40,    # отрицательное демпфирование (регенеративные колебания)
        "chat_amp": 1.60,   # амплитуда насыщения автоколебаний

        # --- закалка ---
        "a78": -0.35,       # интенсивное охлаждение -> снижение температуры
        "a87": 0.45,        # разность температур -> скорость охлаждения
        "q7": 1.20,         # мощность нагрева (управление u7)
        "h7": 0.90,         # расход охлаждающей среды (управление u8)
        "rad7": 0.10,       # нелинейная теплоотдача излучением
        "b8": 0.70,         # расход охлаждающей среды -> твёрдость
        "h8": 0.25,         # избыточный нагрев снижает твёрдость

        # --- приводы (управляющие воздействия) ---
        "b1": 0.80,         # коррекция положения резца
        "b2": 0.50,         # СОЖ при точении
        "b4": 0.70,         # подача при фрезеровании
        "b5": 0.50,         # СОЖ при фрезеровании
        "b6": 0.90,         # демпфирование/жёсткость при фрезеровании

        # --- динамика износа инструмента (насыщающийся закон износа) ---
        "vb_max": 2.0,      # предельный износ (насыщение), ед. карты
        "t_wear": 300.0,    # постоянная времени износа, с
        "wear_d1": 0.45,    # вклад износа в размерную погрешность (точение)
        "wear_d2": 0.30,    # вклад износа в шероховатость (точение)
        "wear_d4": 0.35,    # вклад износа в силу резания (фрезерование)
        "wear_d5": 0.25,    # вклад износа в шероховатость (фрезерование)
        "chat_wear": 0.25,  # рост самовозбуждения чаттера с износом

        # --- программы уставки g(t) ---
        "prog_amp": np.array([1.60, 1.10, 2.40, 1.40, 1.00, 2.00, 8.00, 3.00]),
        "prog_period": np.array([160.0, 95.0, 140.0, 100.0, 120.0, 180.0, 1.0, 1.0]),
        "heat_end": 40.0,    # конец нагрева при закалке, с
        "hold_end": 85.0,    # конец выдержки при закалке, с
        "cool_end": 150.0,   # конец охлаждения при закалке, с
        "tau_cool": 45.0,    # постоянная времени экспоненциального охлаждения, с
        "cool_ramp": 12.0,   # плавность открытия клапана СОЖ, с
        "t_equil": 200.0,    # горизонт осреднения для equilibrium(), с

        # --- структурные матрицы (инициализируются в __init__) ---
        "k_g": np.ones(8),              # чувствительность каналов к программе g(t)
        "c": np.zeros((8, 8)),          # матрица кросс-связей c_ij (собирается из a_ij)
        "b": np.zeros((8, 8)),          # матрица эффективностей управления b_ij
    }

    # ожидаемые формы структурных параметров при переопределении
    _SHAPES = {"k_g": (8,), "c": (8, 8), "b": (8, 8)}

    def __init__(self, params: dict | None = None):
        """
        Параметры модели.

        Parameters
        ----------
        params : dict | None
            Переопределение параметров по умолчанию, словарь {имя: значение}.
            Например, ``{"tau": [...]}``, ``{"chat_mu": 1.2}``. Структурные
            матрицы ``"c"`` (8x8) и ``"b"`` (8x8) можно задать целиком; если они
            не заданы, матрицы собираются из скалярных коэффициентов a_ij/b*.
        """
        self.params = {}
        for key, value in self.DEFAULTS.items():
            if isinstance(value, np.ndarray):
                self.params[key] = value.astype(float).copy()
            else:
                self.params[key] = float(value)

        if params:
            unknown = set(params) - set(self.params)
            if unknown:
                raise KeyError(f"Неизвестные параметры: {sorted(unknown)}")
            for key, value in params.items():
                shape = self._SHAPES.get(key)
                if key == "c" or key == "b":
                    arr = np.asarray(value, dtype=float)
                    if arr.shape != shape:
                        raise ValueError(
                            f"Параметр {key!r} должен иметь форму {shape}"
                        )
                    self.params[key] = arr.copy()
                elif isinstance(self.params[key], np.ndarray):
                    arr = np.asarray(value, dtype=float).ravel()
                    if arr.size == 1:
                        arr = np.full(shape if shape else (self.N_STATES,),
                                      float(arr[0]))
                    if arr.size != (shape[0] if shape else self.N_STATES):
                        raise ValueError(
                            f"Параметр {key!r} должен иметь длину "
                            f"{shape[0] if shape else self.N_STATES}"
                        )
                    self.params[key] = arr.copy()
                else:
                    self.params[key] = float(value)

        # быстрый доступ к часто используемым векторам
        self.x_nom = self.params["x_nom"]
        self.tol = self.params["tol"]
        self.tau = self.params["tau"]
        self.T_EQUIL = self.params["t_equil"]

        # --- структурные матрицы кросс-связей c_ij и управления b_ij ---
        user_c = params.get("c") if params else None
        user_b = params.get("b") if params else None
        if user_c is not None:
            self.c = np.asarray(self.params["c"], dtype=float)
        else:
            # собираем из скалярных коэффициентов (с учётом их переопределений)
            self.c = np.zeros((self.N_STATES, self.N_STATES), dtype=float)
            for (i, j), key in self.COUPLING_MAP.items():
                self.c[i, j] = float(self.params[key])
        if user_b is not None:
            self.b = np.asarray(self.params["b"], dtype=float)
        else:
            self.b = np.zeros((self.N_STATES, self.N_STATES), dtype=float)
            for (i, j), (key, sign) in self.CONTROL_MAP.items():
                self.b[i, j] = sign * float(self.params[key])
        self.params["c"] = self.c   # для прозрачности при интроспекции
        self.params["b"] = self.b

        # чувствительность каналов к программе g(t) (по умолчанию единичные)
        self.k_g = np.asarray(self.params["k_g"], dtype=float).ravel()

    # ------------------------------------------------------------------
    # Вспомогательные функции
    # ------------------------------------------------------------------
    @staticmethod
    def _smoothstep(edge0: float, edge1: float, t) -> np.ndarray:
        """Гладкий переход 0 -> 1 (C1-непрерывный) на интервале [edge0, edge1].

        Поддерживает массивное время: при t формы (n,) возвращается (n,).
        """
        t = np.asarray(t, dtype=float)
        if edge1 <= edge0:
            return np.where(t >= edge1, 1.0, 0.0)
        s = np.clip((t - edge0) / (edge1 - edge0), 0.0, 1.0)
        return s * s * (3.0 - 2.0 * s)

    def _wear(self, t) -> np.ndarray:
        """Насыщающийся закон износа инструмента: w(t) = VB*(1 - exp(-t/t_wear)).

        Износ растёт со временем и выходит на предел VB (насыщение),
        что смещает размер, шероховатость и коэффициент самовозбуждения
        чаттера. Поддерживает массивное время.
        """
        p = self.params
        t = np.maximum(np.asarray(t, dtype=float), 0.0)
        return float(p["vb_max"]) * (1.0 - np.exp(-t / float(p["t_wear"])))

    # ------------------------------------------------------------------
    # API
    # ------------------------------------------------------------------
    def initial_state(self) -> np.ndarray:
        """Начальное состояние — центры контрольных карт, shape (8,)."""
        return self.x_nom.copy()

    def setpoint(self, t) -> np.ndarray:
        """
        Уставка g(t) — программа обработки, shape (8,).

        Для точения и фрезерования это плавно меняющийся профиль прохода
        (изменение припуска, подачи и скорости). Для закалки — тепловое
        равновесие по фазам цикла: нагрев (0...40 с), выдержка (40...85 с),
        охлаждение (85...150 с) по экспоненциальной кривой Ньютона с плавным
        открытием клапана СОЖ.

        Поддержка массивного времени: при t формы (n,) возвращается (n, 8).
        """
        p = self.params
        t = np.asarray(t, dtype=float)
        amp = p["prog_amp"]
        period = p["prog_period"]
        g = np.empty(t.shape + (self.N_STATES,), dtype=float)
        g[...] = self.x_nom
        two_pi = 2.0 * np.pi

        # --- токарная обработка: плавный профиль прохода ---
        # Периодическая составляющая с нулём в t = 0, чтобы старт совпадал
        # с центром карты; разные периоды отражают разные переходы программы.
        g[..., 0] = self.x_nom[0] + amp[0] * (1.0 - np.cos(two_pi * t / period[0]))
        g[..., 1] = self.x_nom[1] + amp[1] * np.sin(two_pi * t / period[1])
        g[..., 2] = self.x_nom[2] + amp[2] * (1.0 - np.cos(two_pi * t / period[2]))

        # --- фрезерная обработка: изменение силового режима и вибрации ---
        g[..., 3] = self.x_nom[3] + amp[3] * (1.0 - np.cos(two_pi * t / period[3]))
        g[..., 4] = self.x_nom[4] + amp[4] * np.sin(two_pi * t / period[4])
        # чаттер задаётся плавным ростом и спадом вдоль прохода
        g[..., 5] = self.x_nom[5] + amp[5] * (1.0 - np.cos(two_pi * t / period[5]))

        # --- закалка: тепловое равновесие по фазам цикла ---
        heat = self._smoothstep(0.0, p["heat_end"], t)
        hold = self._smoothstep(p["heat_end"], p["hold_end"], t)
        cool = self._smoothstep(p["hold_end"], p["cool_end"], t)
        # фаза охлаждения: экспоненциальная кривая Ньютона (отвод тепла
        # пропорционален разности температур), клапан СОЖ открывается
        # плавно в течение cool_ramp секунд, чтобы не было скачка мощности
        z_cool = np.maximum(t - float(p["hold_end"]), 0.0)
        ramp = self._smoothstep(float(p["hold_end"]),
                                float(p["hold_end"]) + float(p["cool_ramp"]), t)
        exp_cool = 1.0 - np.exp(-z_cool / float(p["tau_cool"]))
        # температура растёт при нагреве, стабилизируется на выдержке и падает
        # при охлаждении; текущий уровень определяется интегралом программы.
        g[..., 6] = (self.x_nom[6]
                     + amp[6] * heat
                     - 1.5 * amp[6] * ramp * exp_cool)
        # интенсивность охлаждения/твёрдость: при нагреве ниже номинала,
        # при охлаждении возрастает; небольшой вклад выдержки.
        g[..., 7] = (self.x_nom[7]
                     - 0.4 * amp[7] * heat
                     + amp[7] * cool
                     + 0.15 * amp[7] * hold)
        return g

    def tolerance(self) -> np.ndarray:
        """Допустимая полоса ±δ_i для каждого показателя, shape (8,), δ_i > 0."""
        return self.tol.copy()

    def derivatives(self, x: np.ndarray, u: np.ndarray, t) -> np.ndarray:
        """
        Правые части ОДУ dx/dt, shape (8,).

        u — вектор управляющих воздействий (по одному на показатель):
          u1 — коррекция положения резца (уменьшает размерную погрешность);
          u2 — расход СОЖ при точении (снижает шероховатость и температуру);
          u3 — скорость резания (увеличивает тепловыделение);
          u4 — подача при фрезеровании (увеличивает силу резания);
          u5 — расход СОЖ при фрезеровании (снижает шероховатость);
          u6 — демпфирование/жёсткость (подавляет вибрацию);
          u7 — мощность нагрева при закалке;
          u8 — расход охлаждающей среды при закалке.

        Поддержка массивного времени: при t формы (n,) и x, u формы (8,)
        возвращается массив (n, 8) — используется усреднённым полем в
        equilibrium().
        """
        x = np.asarray(x, dtype=float).reshape(self.N_STATES)
        u = np.asarray(u, dtype=float).reshape(self.N_STATES)
        g = self.setpoint(t)                 # (8,) или (n, 8)
        d = x - g                            # отклонения от программы
        p = self.params
        c = self.c                           # матрица кросс-связей c_ij
        b = self.b                           # матрица эффективностей b_ij
        kg = self.k_g                        # чувствительность к программе

        w = self._wear(t)                    # износ: скаляр или (n,)
        # износ расширяет зону неустойчивости регенеративного чаттера
        mu_eff = float(p["chat_mu"]) * (1.0 + float(p["chat_wear"]) * w)

        dx = []

        # === 1. Токарная обработка: размерная погрешность/износ резца ===
        # d1 растёт от теплового расширения (d3), ускоренного износа при
        # перегреве и детерминированного насыщающегося тренда износа;
        # коррекция положения резца u1 компенсирует погрешность.
        dx.append((kg[0] * g[..., 0] - x[0]
                   + c[0, 2] * d[..., 2]
                   + float(p["wear_gain"]) * np.tanh(d[..., 2] / float(p["wear_scale"]))
                   + float(p["wear_d1"]) * w
                   + b[0, 0] * u[0]) / p["tau"][0])

        # === 2. Токарная обработка: шероховатость поверхности ===
        # Износ резца (в т.ч. насыщающийся trend износа) и высокая температура
        # резания увеличивают Ra; подача СОЖ u2 улучшает условия резания.
        dx.append((kg[1] * g[..., 1] - x[1]
                   + c[1, 0] * d[..., 0]
                   + c[1, 2] * np.tanh(d[..., 2] / 2.0)
                   + float(p["wear_d2"]) * w
                   + b[1, 1] * u[1]) / p["tau"][1])

        # === 3. Токарная обработка: температура в зоне резания ===
        # Тепловыделение от трения изношенного резца и работы разрушения;
        # нагрев пропорционален скорости резания u3, охлаждение — расходу СОЖ.
        # Нелинейный член описывает теплоотдачу (в т.ч. излучением) при
        # отклонении температуры от программной.
        dx.append((kg[2] * g[..., 2] - x[2]
                   + c[2, 0] * np.tanh(d[..., 0] / 2.0)
                   + c[2, 1] * d[..., 1]
                   + b[2, 2] * u[2]
                   + b[2, 1] * u[1]
                   - float(p["rad7"]) * np.tanh(d[..., 2] / 5.0)) / p["tau"][2])

        # === 4. Фрезерная обработка: сила резания ===
        # Сила растёт с шероховатостью (трение по обработанной поверхности) и
        # с амплитудой вибрации; подача u4 увеличивает съём и силу резания.
        dx.append((kg[3] * g[..., 3] - x[3]
                   + c[3, 4] * d[..., 4]
                   + c[3, 5] * d[..., 5]
                   + float(p["wear_d4"]) * w
                   + b[3, 3] * u[3]) / p["tau"][3])

        # === 5. Фрезерная обработка: шероховатость ===
        # Сила резания вызывает упругие отжатия, а вибрация оставляет следы
        # на поверхности; износ зубьев фрезы увеличивает Ra; СОЖ u5 снижает
        # шероховатость.
        dx.append((kg[4] * g[..., 4] - x[4]
                   + c[4, 3] * np.tanh(d[..., 3] / 2.0)
                   + c[4, 5] * np.tanh(d[..., 5] / 2.0) ** 2
                   + float(p["wear_d5"]) * w
                   + b[4, 4] * u[4]) / p["tau"][4])

        # === 6. Фрезерная обработка: вибрация/чаттер ===
        # Уравнение амплитуды автоколебаний типа Ландау-Стюарта: сила резания
        # возбуждает колебания, отрицательное демпфирование соответствует
        # регенеративному механизму чаттера, кубический член даёт насыщение —
        # ограничивает амплитуду биения. С износом инструмента коэффициент
        # самовозбуждения растёт (расширение зоны неустойчивости),
        # демпфирование u6 подавляет вибрацию.
        dx.append((kg[5] * g[..., 5] - x[5]
                   + c[5, 3] * np.tanh(d[..., 3] / 2.0)
                   + mu_eff * d[..., 5] * (1.0 - (d[..., 5] / float(p["chat_amp"])) ** 2)
                   + b[5, 5] * u[5]) / p["tau"][5])

        # === 7. Закалка: температура заготовки ===
        # Нагрев u7 повышает температуру, охлаждающая среда u8 и интенсивное
        # охлаждение d8 понижают её; излучение описано нелинейным стоком.
        dx.append((kg[6] * g[..., 6] - x[6]
                   + c[6, 7] * d[..., 7]
                   + b[6, 6] * u[6]
                   + b[6, 7] * u[7]
                   - float(p["rad7"]) * np.tanh(d[..., 6] / 6.0)) / p["tau"][6])

        # === 8. Закалка: интенсивность охлаждения/твёрдость ===
        # Скорость охлаждения определяется разностью температур (d7), растёт
        # с расходом охлаждающей среды u8; избыточный нагрев u7 снижает
        # достигаемую твёрдость.
        dx.append((kg[7] * g[..., 7] - x[7]
                   + c[7, 6] * np.tanh(d[..., 6] / 6.0)
                   + b[7, 7] * u[7]
                   + b[7, 6] * u[6]) / p["tau"][7])

        return np.stack(dx, axis=-1)

    def step(self, x: np.ndarray, u: np.ndarray, dt: float, t: float,
             noise: np.ndarray | None = None,
             disturbance: np.ndarray | None = None) -> np.ndarray:
        """
        Один шаг интегрирования методом Рунге-Кутты 4-го порядка, shape (8,).

        noise — аддитивный шум к правой части (быстрые флуктуации процесса);
        disturbance — детерминированное возмущение (тренд износа, скачок
        вибрации, недостаточное охлаждение и т.п.), также добавляемое к dx/dt.
        """
        x = np.asarray(x, dtype=float).reshape(self.N_STATES)
        u = np.asarray(u, dtype=float).reshape(self.N_STATES)
        dt = float(dt)

        extra = np.zeros(self.N_STATES, dtype=float)
        if noise is not None:
            extra += np.asarray(noise, dtype=float).reshape(self.N_STATES)
        if disturbance is not None:
            extra += np.asarray(disturbance, dtype=float).reshape(self.N_STATES)

        def f(state: np.ndarray, time: float) -> np.ndarray:
            return self.derivatives(state, u, time) + extra

        k1 = f(x, t)
        k2 = f(x + 0.5 * dt * k1, t + 0.5 * dt)
        k3 = f(x + 0.5 * dt * k2, t + 0.5 * dt)
        k4 = f(x + dt * k3, t + dt)
        return x + (dt / 6.0) * (k1 + 2.0 * k2 + 2.0 * k3 + k4)

    def equilibrium(self) -> tuple[np.ndarray, np.ndarray]:
        """
        Точка равновесия (x*, u*), shape (8,) и (8,).

        Точный расчёт равновесия усреднённым полем: уставка зависит от t,
        поэтому ищется неподвижная точка осреднённой на горизонте
        [0, T_EQUIL] правой части. Осреднённое поле релаксируется к
        равновесию методом Рунге-Кутты 4-го порядка (RK4 по циклу);
        u* — номинальное (нулевое) воздействие программы.
        """
        u_zero = np.zeros(self.N_STATES, dtype=float)
        ts = np.linspace(0.0, self.T_EQUIL, 161)

        # старт — среднее значение программы за цикл осреднения
        x_eq = np.mean(self.setpoint(ts), axis=0)

        # рефаксация усреднённого поля методом Рунге-Кутты 4
        h = 2.0
        for _ in range(400):
            mean_field = lambda s: np.mean(self.derivatives(s, u_zero, ts), axis=0)
            k1 = mean_field(x_eq)
            k2 = mean_field(x_eq + 0.5 * h * k1)
            k3 = mean_field(x_eq + 0.5 * h * k2)
            k4 = mean_field(x_eq + h * k3)
            x_eq = x_eq + (h / 6.0) * (k1 + 2.0 * k2 + 2.0 * k3 + k4)
            if np.max(np.abs(k1)) < 1e-10:
                break
        return x_eq, u_zero


