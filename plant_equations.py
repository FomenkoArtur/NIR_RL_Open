"""
Физическая модель участка металлообработки: 8 связанных нелинейных ОДУ.

Модуль дополняет цифровой двойник `plant.py`, но не заменяет его: в `plant.py`
остаются калибровка карт Шухарта, робастная нормализация и веса. Здесь описана
только динамика технологического процесса, поэтому импортируется лишь `numpy`.

Состояние x(t) — восемь показателей в шкале контрольных карт (центр около 100):

    токарная обработка
      x1 — размерная погрешность/износ вершины резца;
      x2 — шероховатость обработанной поверхности Ra;
      x3 — температура в зоне резания;
    фрезерная обработка
      x4 — сила резания (упругое отжатие инструмента);
      x5 — шероховатость обработанной поверхности;
      x6 — амплитуда вибрации (регенеративный чаттер);
    закалка
      x7 — температура заготовки;
      x8 — интенсивность охлаждения / показатель твёрдости.

Показатели приведены к безразмерной шкале карты (100 — центр калибровки).
Для температур это аффинное преобразование, поэтому коэффициенты уравнений
имеют размерность 1/с и допускают единую запись для разных операций.

Принятые допущения (разд. 3.1.1):
  * параметры сосредоточенные, поле температур и напряжений по объёму
    осреднено;
  * тренд износа инструмента и тепловые постоянные меняются медленно по
    сравнению с тактом управления;
  * уставка g(t) — программа обработки, а не константа: при точении и
    фрезеровании она плавно меняется вдоль прохода, при закалке задаёт цикл
    «нагрев → выдержка → охлаждение»;
  * аддитивный шум описывает быстрые флуктуации процесса, детерминированное
    возмущение — тренд износа, скачок вибрации или недостаточное охлаждение.

Все уравнения записаны через отклонения d_i(t) = x_i(t) - g_i(t) от программы.
Поэтому при d = 0 и u = 0 процесс находится на программной траектории, а
возмущения и управление выводят его из равновесия. Связи между уравнениями
отражают реальные механизмы: тепловое расширение, износ резца, рост
шероховатости, силы резания, автоколебания и тепловой баланс закалки.
"""

from __future__ import annotations

import numpy as np


class PlantODESystem:
    """Связанная физическая модель 8 показателей участка металлообработки."""

    N_STATES = 8                     # x1...x8
    T_EQUIL = 200.0                  # горизонт осреднения для equilibrium(), с

    # Параметры по умолчанию. Любой ключ можно переопределить через params.
    DEFAULTS = {
        # центры контрольных карт (близки к plant.x_bar при BETA = 100)
        "x_nom": np.array([100.03, 100.20, 100.22, 100.40,
                           100.17, 99.97, 100.11, 99.91]),
        # допустимые полосы ±δ_i
        "tol": np.array([1.50, 1.20, 2.50, 1.80, 1.20, 2.20, 3.50, 2.00]),
        # постоянные времени звеньев, с: тепловые процессы инерционнее силовых
        "tau": np.array([18.0, 10.0, 7.0, 9.0, 12.0, 10.0, 35.0, 22.0]),

        # --- токарная обработка ---
        "a13": 0.35,        # тепловое расширение детали/резца -> размерная погрешность
        "wear_gain": 0.18,  # ускоренный износ при перегреве зоны резания
        "wear_scale": 2.0,  # масштаб нелинейности износа
        "a21": 0.45,        # износ резца -> рост шероховатости
        "a23": 0.35,        # температура резания -> рост шероховатости
        "a31": 0.30,        # трение изношенного резца -> дополнительный нагрев
        "a32": 0.20,        # работа разрушения при большой шероховатости -> нагрев
        "q3": 0.60,         # нагрев от скорости резания (управление u3)
        "h3": 0.45,         # охлаждение СОЖ (управление u2)

        # --- фрезерная обработка ---
        "a45": 0.35,        # шероховатость -> сила резания
        "a46": 0.45,        # вибрация -> динамическая сила резания
        "a54": 0.55,        # сила резания -> шероховатость
        "a56": 0.40,        # следы вибрации -> шероховатость
        "a64": 0.60,        # сила резания возбуждает чаттер
        "chat_mu": 1.40,    # отрицательное демпфирование (регенеративные колебания)
        "chat_amp": 1.60,   # амплитуда насыщения автоколебаний

        # --- закалка ---
        "a78": -0.35,       # интенсивное охлаждение -> снижение температуры
        "a87": 0.45,        # разность температур -> скорость охлаждения
        "q7": 1.20,         # мощность нагрева (управление u7)
        "h7": 0.90,         # расход охлаждающей среды (управление u8)
        "rad7": 0.10,       # нелинейная теплоотдача излучением
        "b8": 0.70,         # расход охлаждающей среды -> твёрдость
        "h8": 0.25,         # избыточный нагрев снижает твёрдость

        # --- приводы (управляющие воздействия) ---
        "b1": 0.80,         # коррекция положения резца
        "b2": 0.50,         # СОЖ при точении
        "b4": 0.70,         # подача при фрезеровании
        "b5": 0.50,         # СОЖ при фрезеровании
        "b6": 0.90,         # демпфирование/жёсткость при фрезеровании

        # --- программы уставки g(t) ---
        "prog_amp": np.array([1.60, 1.10, 2.40, 1.40, 1.00, 2.00, 8.00, 3.00]),
        "prog_period": np.array([160.0, 95.0, 140.0, 100.0, 120.0, 180.0, 1.0, 1.0]),
        "heat_end": 40.0,    # конец нагрева при закалке, с
        "hold_end": 85.0,    # конец выдержки при закалке, с
        "cool_end": 150.0,   # конец охлаждения при закалке, с
        "t_equil": 200.0,    # горизонт осреднения для equilibrium(), с
    }

    def __init__(self, params: dict | None = None):
        """
        Параметры модели.

        Parameters
        ----------
        params : dict | None
            Переопределение параметров по умолчанию, словарь {имя: значение}.
            Например, ``{"tau": [...]}``, ``{"chat_mu": 1.2}``.
        """
        self.params = {}
        for key, value in self.DEFAULTS.items():
            if isinstance(value, np.ndarray):
                self.params[key] = value.astype(float).copy()
            else:
                self.params[key] = float(value)

        if params:
            unknown = set(params) - set(self.params)
            if unknown:
                raise KeyError(f"Неизвестные параметры: {sorted(unknown)}")
            for key, value in params.items():
                if isinstance(self.params[key], np.ndarray):
                    arr = np.asarray(value, dtype=float).ravel()
                    if arr.size == 1:
                        arr = np.full(self.N_STATES, float(arr[0]))
                    if arr.size != self.N_STATES:
                        raise ValueError(
                            f"Параметр {key!r} должен иметь длину {self.N_STATES}"
                        )
                    self.params[key] = arr.copy()
                else:
                    self.params[key] = float(value)

        # быстрый доступ к часто используемым векторам
        self.x_nom = self.params["x_nom"]
        self.tol = self.params["tol"]
        self.tau = self.params["tau"]
        self.T_EQUIL = self.params["t_equil"]

    # ------------------------------------------------------------------
    # Вспомогательные функции
    # ------------------------------------------------------------------
    @staticmethod
    def _smoothstep(edge0: float, edge1: float, t: float) -> float:
        """Гладкий переход 0 -> 1 (C1-непрерывный) на интервале [edge0, edge1]."""
        if edge1 <= edge0:
            return 1.0 if t >= edge1 else 0.0
        s = min(1.0, max(0.0, (t - edge0) / (edge1 - edge0)))
        return s * s * (3.0 - 2.0 * s)

    # ------------------------------------------------------------------
    # API
    # ------------------------------------------------------------------
    def initial_state(self) -> np.ndarray:
        """Начальное состояние — центры контрольных карт, shape (8,)."""
        return self.x_nom.copy()

    def setpoint(self, t: float) -> np.ndarray:
        """
        Уставка g(t) — программа обработки, shape (8,).

        Для точения и фрезерования это плавно меняющийся профиль прохода
        (изменение припуска, подачи и скорости). Для закалки — кусочно-гладкий
        цикл: нагрев (0...40 с), выдержка (40...85 с), охлаждение (85...150 с).
        """
        p = self.params
        g = self.x_nom.copy()
        amp = p["prog_amp"]
        period = p["prog_period"]

        # --- токарная обработка: плавный профиль прохода ---
        # Периодическая составляющая с нулём в t = 0, чтобы старт совпадал
        # с центром карты; разные периоды отражают разные переходы программы.
        g[0] += amp[0] * (1.0 - np.cos(2.0 * np.pi * t / period[0]))
        g[1] += amp[1] * np.sin(2.0 * np.pi * t / period[1])
        g[2] += amp[2] * (1.0 - np.cos(2.0 * np.pi * t / period[2]))

        # --- фрезерная обработка: изменение силового режима и вибрации ---
        g[3] += amp[3] * (1.0 - np.cos(2.0 * np.pi * t / period[3]))
        g[4] += amp[4] * np.sin(2.0 * np.pi * t / period[4])
        # чаттер задаётся плавным ростом и спадом вдоль прохода
        g[5] += amp[5] * (1.0 - np.cos(2.0 * np.pi * t / period[5]))

        # --- закалка: нагрев -> выдержка -> охлаждение ---
        heat = self._smoothstep(0.0, p["heat_end"], t)
        hold = self._smoothstep(p["heat_end"], p["hold_end"], t)
        cool = self._smoothstep(p["hold_end"], p["cool_end"], t)
        # температура растёт при нагреве, стабилизируется на выдержке и падает
        # при охлаждении; текущий уровень определяется интегралом программы.
        g[6] += amp[6] * heat - 1.5 * amp[6] * cool
        # интенсивность охлаждения/твёрдость: при нагреве ниже номинала,
        # при охлаждении возрастает; небольшой вклад выдержки.
        g[7] += -0.4 * amp[7] * heat + amp[7] * cool + 0.15 * amp[7] * hold
        return g

    def tolerance(self) -> np.ndarray:
        """Допустимая полоса ±δ_i для каждого показателя, shape (8,), δ_i > 0."""
        return self.tol.copy()

    def derivatives(self, x: np.ndarray, u: np.ndarray, t: float) -> np.ndarray:
        """
        Правые части ОДУ dx/dt, shape (8,).

        u — вектор управляющих воздействий (по одному на показатель):
          u1 — коррекция положения резца (уменьшает размерную погрешность);
          u2 — расход СОЖ при точении (снижает шероховатость и температуру);
          u3 — скорость резания (увеличивает тепловыделение);
          u4 — подача при фрезеровании (увеличивает силу резания);
          u5 — расход СОЖ при фрезеровании (снижает шероховатость);
          u6 — демпфирование/жёсткость (подавляет вибрацию);
          u7 — мощность нагрева при закалке;
          u8 — расход охлаждающей среды при закалке.
        """
        x = np.asarray(x, dtype=float).reshape(self.N_STATES)
        u = np.asarray(u, dtype=float).reshape(self.N_STATES)
        g = self.setpoint(t)
        d = x - g
        p = self.params

        dx = np.empty(self.N_STATES, dtype=float)

        # === 1. Токарная обработка: размерная погрешность/износ резца ===
        # d1 растёт от теплового расширения (d3) и ускоренного износа при
        # перегреве; коррекция положения резца u1 компенсирует погрешность.
        dx[0] = (-d[0]
                 + p["a13"] * d[2]
                 + p["wear_gain"] * np.tanh(d[2] / p["wear_scale"])
                 - p["b1"] * u[0]) / p["tau"][0]

        # === 2. Токарная обработка: шероховатость поверхности ===
        # Износ резца и высокая температура резания увеличивают Ra;
        # подача СОЖ u2 улучшает условия резания и снижает шероховатость.
        dx[1] = (-d[1]
                 + p["a21"] * d[0]
                 + p["a23"] * np.tanh(d[2] / 2.0)
                 - p["b2"] * u[1]) / p["tau"][1]

        # === 3. Токарная обработка: температура в зоне резания ===
        # Тепловыделение от трения изношенного резца и работы разрушения;
        # нагрев пропорционален скорости резания u3, охлаждение — расходу СОЖ.
        # Нелинейный член описывает теплоотдачу (в т.ч. излучением) при
        # отклонении температуры от программной.
        dx[2] = (-d[2]
                 + p["a31"] * np.tanh(d[0] / 2.0)
                 + p["a32"] * d[1]
                 + p["q3"] * u[2]
                 - p["h3"] * u[1]
                 - p["rad7"] * np.tanh(d[2] / 5.0)) / p["tau"][2]

        # === 4. Фрезерная обработка: сила резания ===
        # Сила растёт с шероховатостью (трение по обработанной поверхности) и
        # с амплитудой вибрации; подача u4 увеличивает съём и силу резания.
        dx[3] = (-d[3]
                 + p["a45"] * d[4]
                 + p["a46"] * d[5]
                 + p["b4"] * u[3]) / p["tau"][3]

        # === 5. Фрезерная обработка: шероховатость ===
        # Сила резания вызывает упругие отжатия, а вибрация оставляет следы
        # на поверхности; СОЖ u5 снижает шероховатость.
        dx[4] = (-d[4]
                 + p["a54"] * np.tanh(d[3] / 2.0)
                 + p["a56"] * np.tanh(d[5] / 2.0) ** 2
                 - p["b5"] * u[4]) / p["tau"][4]

        # === 6. Фрезерная обработка: вибрация/чаттер ===
        # Уравнение амплитуды автоколебаний типа Ландау-Стюарта:
        # сила резания возбуждает колебания, отрицательное демпфирование
        # соответствует регенеративному механизму чаттера, а кубический член
        # ограничивает амплитуду. Демпфирование u6 подавляет вибрацию.
        dx[5] = (-d[5]
                 + p["a64"] * np.tanh(d[3] / 2.0)
                 + p["chat_mu"] * d[5] * (1.0 - (d[5] / p["chat_amp"]) ** 2)
                 - p["b6"] * u[5]) / p["tau"][5]

        # === 7. Закалка: температура заготовки ===
        # Нагрев u7 повышает температуру, охлаждающая среда u8 и интенсивное
        # охлаждение d8 понижают её; излучение описано нелинейным стоком.
        dx[6] = (-d[6]
                 + p["a78"] * d[7]
                 + p["q7"] * u[6]
                 - p["h7"] * u[7]
                 - p["rad7"] * np.tanh(d[6] / 6.0)) / p["tau"][6]

        # === 8. Закалка: интенсивность охлаждения/твёрдость ===
        # Скорость охлаждения определяется разностью температур (d7), растёт
        # с расходом охлаждающей среды u8; избыточный нагрев u7 снижает
        # достигаемую твёрдость.
        dx[7] = (-d[7]
                 + p["a87"] * np.tanh(d[6] / 6.0)
                 + p["b8"] * u[7]
                 - p["h8"] * u[6]) / p["tau"][7]

        return dx

    def step(self, x: np.ndarray, u: np.ndarray, dt: float, t: float,
             noise: np.ndarray | None = None,
             disturbance: np.ndarray | None = None) -> np.ndarray:
        """
        Один шаг интегрирования методом Рунге-Кутты 4-го порядка, shape (8,).

        noise — аддитивный шум к правой части (быстрые флуктуации процесса);
        disturbance — детерминированное возмущение (тренд износа, скачок
        вибрации, недостаточное охлаждение и т.п.), также добавляемое к dx/dt.
        """
        x = np.asarray(x, dtype=float).reshape(self.N_STATES)
        u = np.asarray(u, dtype=float).reshape(self.N_STATES)
        dt = float(dt)

        extra = np.zeros(self.N_STATES, dtype=float)
        if noise is not None:
            extra += np.asarray(noise, dtype=float).reshape(self.N_STATES)
        if disturbance is not None:
            extra += np.asarray(disturbance, dtype=float).reshape(self.N_STATES)

        def f(state: np.ndarray, time: float) -> np.ndarray:
            return self.derivatives(state, u, time) + extra

        k1 = f(x, t)
        k2 = f(x + 0.5 * dt * k1, t + 0.5 * dt)
        k3 = f(x + 0.5 * dt * k2, t + 0.5 * dt)
        k4 = f(x + dt * k3, t + dt)
        return x + (dt / 6.0) * (k1 + 2.0 * k2 + 2.0 * k3 + k4)

    def equilibrium(self) -> tuple[np.ndarray, np.ndarray]:
        """
        Точка равновесия (x*, u*), shape (8,) и (8,).

        Из-за переменной программы g(t) равновесие зависит от времени, поэтому
        возвращается среднее на горизонте [0, T_EQUIL]. x* находится как
        неподвижная точка осреднённой правой части при u* = 0.
        """
        t_span = np.linspace(0.0, self.T_EQUIL, 81)
        g_mean = np.mean(np.array([self.setpoint(t) for t in t_span]), axis=0)

        x_eq = g_mean.copy()
        u_zero = np.zeros(self.N_STATES, dtype=float)
        for _ in range(200):
            mean_dx = np.zeros(self.N_STATES, dtype=float)
            for t in t_span:
                mean_dx += self.derivatives(x_eq, u_zero, t)
            mean_dx /= len(t_span)
            x_eq = x_eq + 0.8 * mean_dx
            if np.max(np.abs(mean_dx)) < 1e-10:
                break
        return x_eq, u_zero
